export function AgentStreamBlocks({
  steps, 
  textContent,
  isStreaming,
  thinkingDuration,
  enableTextStreaming = false,
  validation,
  autoFix,
  pendingMigration,
  runSummary,
  timelineEvents,
  versionDiff,
  onMigrationApprove,
  onMigrationReject
}: AgentStreamBlocksProps) {
  const [showDetails, setShowDetails] = useState(false);
  const visibleTimelineEvents = useMemo(() => {
    if (!timelineEvents || timelineEvents.length === 0) return [];
    const compact = timelineEvents.filter(
      (event) => event.eventType !== 'text' && event.eventType !== 'other'
    );
    const deduped: ChatTimelineEvent[] = [];
    for (const event of compact) {
      const prev = deduped[deduped.length - 1];
      const key = `${event.eventType}:${event.label}:${event.path || ''}:${event.status}`;
      const prevKey = prev
        ? `${prev.eventType}:${prev.label}:${prev.path || ''}:${prev.status}`
        : '';
      if (key === prevKey) continue;
      deduped.push(event);
    }
    return deduped.slice(-8);
  }, [timelineEvents]);

  // Group steps into blocks for display
  const blocks = useMemo(() => {
    const result: Array<{
      type: 'thought' | 'text' | 'tools' | 'read' | 'edit' | 'edits' | 'database' | 'db_logs' | 'validation' | 'complete';
      content?: string;
      duration?: number;
      count?: number;
      filename?: string;
      logType?: 'postgres' | 'auth' | 'edge' | 'analytics';
      tools?: AgentStep[];
      edits?: Array<{ path: string; action: string }>;
      validationData?: ValidationState;
      completeData?: {
        summary: string;
        filesCreated?: string[];
        packagesInstalled?: string[];
        validation?: { score: number; errors: number; warnings: number };
        plan?: { architecture: string; tasks: string[] };
      };
      migration?: { 
        sql: string; 
        description?: string; 
        tables?: string[];
        status?: 'pending' | 'approved' | 'rejected' | 'executing' | 'completed' | 'failed';
        result?: {
          success: boolean;
          message?: string;
          results?: Array<{ statement: string; success: boolean; error?: string }>;
        };
        /** Auto-generated migration fields for AutoMigrationCard */
        autoGenerated?: boolean;
        requiresAuth?: boolean;
        features?: string[];
      };
    }> = [];
    
    // Add thinking duration if present
    if (thinkingDuration && thinkingDuration > 0) {
      result.push({ type: 'thought', duration: thinkingDuration });
    }
    
    // Group consecutive text content
    const textParts: string[] = [];
    const toolCalls: AgentStep[] = [];
    const fileEdits: Array<{ path: string; action: string }> = [];
    const filesRead: string[] = [];
    const dbLogsRead: Array<'postgres' | 'auth' | 'edge' | 'analytics'> = [];
    let dbMigration: { sql: string; description?: string; tables?: string[] } | null = null;
    
    steps.forEach((step) => {
      // Collect tool calls
      if (step.type === 'tool_call') {
        toolCalls.push(step);
        
        // Extract path from data OR args (for DB-loaded steps)
        const data = step.data as { path?: string } | undefined;
        const args = step.args as { path?: string } | undefined;
        const path = data?.path || args?.path;
        
        // Check if it's a read operation
        if (step.name?.toLowerCase().includes('read')) {
          if (path) {
            filesRead.push(path);
          }
        }
        
        // Check if it's a file create/edit operation - add to edits
        if (step.name?.toLowerCase().includes('create') || 
            step.name?.toLowerCase().includes('edit') || 
            step.name?.toLowerCase().includes('write')) {
          if (path) {
            const action = step.name?.toLowerCase().includes('create') ? 'created' : 'modified';
            fileEdits.push({ path, action });
          }
        }
        
        // Check for database log reading
        if (step.name?.toLowerCase().includes('analytics') || step.name?.toLowerCase().includes('logs')) {
          const stepName = step.name?.toLowerCase() || '';
          if (stepName.includes('postgres') || stepName.includes('database')) {
            dbLogsRead.push('postgres');
          } else if (stepName.includes('auth')) {
            dbLogsRead.push('auth');
          } else if (stepName.includes('edge') || stepName.includes('function')) {
            dbLogsRead.push('edge');
          } else if (stepName.includes('analytics')) {
            dbLogsRead.push('analytics');
          }
        }
        
        // Check for database migration
        if (step.name?.toLowerCase().includes('migration') || step.name?.toLowerCase().includes('database')) {
          const data = step.data as { sql?: string; query?: string; description?: string; tables?: string[] } | undefined;
          const args = step.args as { sql?: string; query?: string; description?: string; tables?: string[] } | undefined;
          const sql = data?.sql || data?.query || args?.sql || args?.query;
          if (sql) {
            dbMigration = {
              sql,
              description: data?.description || args?.description,
              tables: data?.tables || args?.tables
            };
          }
        }
      }
      
      // Collect file edits from tool results
      if (step.type === 'tool_result') {
        const data = step.data as { path?: string; action?: string } | undefined;
        const args = step.args as { path?: string; action?: string } | undefined;
        const path = data?.path || args?.path;
        const action = data?.action || args?.action;
        
        if (path && action) {
          // Don't duplicate if already added from tool_call
          if (!fileEdits.some(e => e.path === path)) {
            fileEdits.push({ path, action });
          }
        }
      }
      
      // Show only explicit text stream as main chat content.
      // Technical step payloads stay in Details/Timeline.
      if (step.content && step.type === 'text') {
        textParts.push(step.content);
      }
      
      // Collect complete step
      if (step.type === 'complete') {
        const data = step.data as {
          filesCreated?: string[];
          packagesInstalled?: string[];
          validation?: { score: number; errors: number; warnings: number };
          plan?: { architecture: string; tasks: string[] };
        } | undefined;
        
        result.push({
          type: 'complete',
          completeData: {
            summary: step.content || 'Готово!',
            filesCreated: data?.filesCreated,
            packagesInstalled: data?.packagesInstalled,
            validation: data?.validation,
            plan: data?.plan,
          },
        });
      }
    });
    
    // Add text content block
    if (textContent || textParts.length > 0) {
      const rawContent = textContent || textParts.join('\n');
      const content = compactRepeatedText(
        runSummary ? stripRunSummarySection(rawContent) : rawContent
      );
      if (content.trim()) {
        result.push({ type: 'text', content });
      }
    }
    
    // Add tools used block - only if we have valid tools with names
    const validTools = toolCalls.filter(t => t.name && t.name.trim() !== '');
    if (validTools.length > 0) {
      result.push({ type: 'tools', count: validTools.length, tools: validTools });
    }
    
    // Add read files blocks - only if we have actual filenames
    const validReads = filesRead.filter(f => f && f.trim() !== '');
    validReads.forEach(filename => {
      result.push({ type: 'read', filename: filename.split('/').pop() || filename });
    });
    
    // Add edits made block - only if we have valid edits with paths
    const diffEdits = (versionDiff?.filesChanged || []).filter((entry) => entry.path && entry.path.trim() !== '');
    const validEdits = (diffEdits.length > 0 ? diffEdits : fileEdits).filter(e => e.path && e.path.trim() !== '');
    if (validEdits.length > 0) {
      result.push({ type: 'edits', count: validEdits.length, edits: validEdits });
    }
    
    // Add database logs read blocks
    dbLogsRead.forEach(logType => {
      result.push({ type: 'db_logs', logType });
    });
    
    // Add database migration block (from steps or prop)
    if (dbMigration) {
      result.push({ type: 'database', migration: { ...dbMigration, status: 'pending' } });
    } else if (pendingMigration) {
      result.push({ 
        type: 'database', 
        migration: {
          sql: pendingMigration.sql,
          description: pendingMigration.description,
          tables: pendingMigration.tables,
          status: pendingMigration.status,
          result: pendingMigration.result,
          // 🆕 Pass auto-generated migration fields for AutoMigrationCard
          autoGenerated: pendingMigration.autoGenerated,
          requiresAuth: pendingMigration.requiresAuth,
          features: pendingMigration.features,
        }
      });
    }
    
    // Add validation block if available
    if (validation && validation.score !== undefined) {
      result.push({ type: 'validation', validationData: validation });
    }
    
    return result;
  }, [steps, textContent, thinkingDuration, pendingMigration, validation, runSummary, versionDiff]);

  const detailBlockTypes = new Set(['thought', 'tools', 'read', 'edit', 'edits', 'db_logs', 'validation']);
  const primaryBlocks = blocks.filter((block) => !detailBlockTypes.has(block.type));
  const detailBlocks = blocks.filter((block) => detailBlockTypes.has(block.type));

  const renderBlock = (block: (typeof blocks)[number], idx: number, keyPrefix = '') => (
    <motion.div
      key={`${keyPrefix}${block.type}-${idx}`}
      initial={{ opacity: 0, y: 5 }}
      animate={{ opacity: 1, y: 0 }}
      exit={{ opacity: 0, y: -5 }}
      transition={{ delay: idx * 0.05 }}
    >
      {block.type === 'thought' && block.duration && (
        <ThoughtBadge duration={block.duration} />
      )}
      
      {block.type === 'text' && block.content && (
        <div className="text-sm text-foreground leading-relaxed whitespace-pre-wrap">
          {enableTextStreaming ? (
            <StreamingTextByWord 
              text={block.content} 
              speed={30}
              skipAnimation={!isStreaming}
            />
          ) : (
            block.content
          )}
        </div>
      )}
      
      {block.type === 'tools' && block.tools && (
        <ToolsUsedBadge 
          count={block.count || 0} 
          tools={block.tools}
          allSteps={steps}
        />
      )}
      
      {block.type === 'read' && block.filename && (
        <ReadBadge filename={block.filename} />
      )}
      
      {block.type === 'edit' && block.filename && (
        <EditingBadge filename={block.filename} />
      )}
      
      {block.type === 'edits' && block.edits && (
        <EditsMadeBadge count={block.count || 0} edits={block.edits} />
      )}
      
      {block.type === 'db_logs' && block.logType && (
        <ReadDatabaseLogsBadge logType={block.logType} />
      )}
      
      {block.type === 'database' && block.migration && (
        block.migration.autoGenerated ? (
          <AutoMigrationCard 
            migration={{
              id: 'pending-auto-migration',
              sql: block.migration.sql,
              description: block.migration.description,
              tables: block.migration.tables,
              status: block.migration.status || 'pending',
              autoGenerated: true,
              requiresAuth: block.migration.requiresAuth,
              features: block.migration.features,
              result: block.migration.result,
            }}
            onApprove={() => onMigrationApprove?.()}
            onReject={() => onMigrationReject?.()}
            isProcessing={block.migration.status === 'executing'}
          />
        ) : (
          <DatabaseModifiedBadge 
            migration={block.migration}
            status={block.migration.status}
            result={block.migration.result}
            onApprove={onMigrationApprove}
            onReject={onMigrationReject}
          />
        )
      )}
      
      {block.type === 'validation' && block.validationData && (
        <ValidationBadge validation={block.validationData} />
      )}
      
      {block.type === 'complete' && block.completeData && (
        <CompleteSummaryBadge data={block.completeData} />
      )}
    </motion.div>
  );

  return (
    <div className="space-y-1.5">
      <AnimatePresence mode="popLayout">
        {primaryBlocks.map((block, idx) => renderBlock(block, idx))}
      </AnimatePresence>

      {detailBlocks.length > 0 && (
        <Collapsible open={showDetails} onOpenChange={setShowDetails}>
          <CollapsibleTrigger asChild>
            <button className="flex w-full items-center gap-2 rounded-md border border-border/60 bg-background/40 px-2.5 py-1.5 text-xs text-muted-foreground hover:bg-muted/40 transition-colors">
              <ShieldCheck className="w-3.5 h-3.5" />
              <span>Детали ({detailBlocks.length})</span>
              <span className="ml-auto">
                {showDetails ? <ChevronUp className="w-3.5 h-3.5" /> : <ChevronDown className="w-3.5 h-3.5" />}
              </span>
            </button>
          </CollapsibleTrigger>
          <CollapsibleContent>
            <div className="mt-2 space-y-1.5 rounded-md border border-border/50 bg-muted/20 p-2.5">
              <AnimatePresence mode="popLayout">
                {detailBlocks.map((block, idx) => renderBlock(block, idx, 'detail-'))}
              </AnimatePresence>
            </div>
          </CollapsibleContent>
        </Collapsible>
      )}

      {showDetails && visibleTimelineEvents.length > 0 && (
        <div className="rounded-md border border-border/60 bg-muted/20 px-3 py-2">
          <div className="mb-2 text-xs font-medium text-foreground">Хронология</div>
          <div className="space-y-1.5">
            {visibleTimelineEvents.map((event) => (
              <div key={event.id} className="flex items-start gap-2 text-xs">
                <span
                  className={cn(
                    "mt-0.5 inline-block h-1.5 w-1.5 rounded-full",
                    event.status === 'success' && 'bg-green-500',
                    event.status === 'error' && 'bg-red-500',
                    event.status === 'info' && 'bg-blue-500'
                  )}
                />
                <span className="text-muted-foreground">
                  {prettifyTimelineLabel(event)}
                  {event.path ? ` • ${event.path.split('/').pop()}` : ''}
                </span>
              </div>
            ))}
          </div>
        </div>
      )}

      {runSummary && <RunSummaryCard summary={runSummary} />}
      
      {/* Auto-fix indicator - shown at the bottom during auto-fixing */}
      {autoFix && (autoFix.isAutoFixing || autoFix.attempt > 0) && (
        <AutoFixIndicator
          isAutoFixing={autoFix.isAutoFixing}
          attempt={autoFix.attempt}
          maxAttempts={autoFix.maxAttempts}
          currentScore={autoFix.currentScore}
        />
      )}
    </div>
  );
}

export default AgentStreamBlocks;
