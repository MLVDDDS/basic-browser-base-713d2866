function stripRunSummarySection(value: string): string {
  const marker = '\n\nИтог анализа:';
  const idx = value.indexOf(marker);
  if (idx === -1) return value;
  return value.slice(0, idx).trim();
}

function compactRepeatedText(value: string): string {
  const lines = String(value || "").split('\n');
  const compact: string[] = [];
  let prev = '';
  for (const line of lines) {
    const normalized = line.replace(/\s+/g, ' ').trim();
    if (!normalized && prev === '') {
      continue;
    }
    if (normalized && normalized === prev) {
      continue;
    }
    compact.push(line);
    prev = normalized;
  }
  return compact.join('\n').trim();
}

function prettifyTimelineLabel(event: ChatTimelineEvent): string {
  const rawLabel = String(event.label || "").trim();
  const normalizedLabel = rawLabel
    .replace(/^phase\s*[•:]\s*/i, "")
    .replace(/^tool_call\s*[•:]\s*/i, "")
    .replace(/^tool_result\s*[•:]\s*/i, "")
    .replace(/^complete\s*[•:]\s*/i, "")
    .replace(/^validation\s*[•:]\s*/i, "")
    .replace(/^plan\s*[•:]\s*/i, "")
    .trim();

  if (event.eventType === "tool_call") {
    return `Инструмент: ${humanizeToolName(normalizedLabel || rawLabel || "Действие")}`;
  }
  if (event.eventType === "tool_result") {
    return `Результат: ${humanizeToolName(normalizedLabel || rawLabel || "Действие")}`;
  }
  if (event.eventType === "phase") {
    return `Этап: ${normalizedLabel || "выполнение"}`;
  }
  if (event.eventType === "validation") {
    return `Проверка: ${normalizedLabel || "quality gate"}`;
  }
  if (event.eventType === "plan") {
    return `План: ${normalizedLabel || "подготовлен"}`;
  }
  if (event.eventType === "thinking") {
    return `Анализ: ${normalizedLabel || "в процессе"}`;
  }
  if (event.eventType === "complete") {
    return `Финиш: ${normalizedLabel || "завершено"}`;
  }
  return rawLabel || event.eventType;
}

