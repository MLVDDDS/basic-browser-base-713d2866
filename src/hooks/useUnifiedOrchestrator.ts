/**
 * Unified Orchestrator Hook
 * 
 * Single orchestrator with 4 modes:
 * - LIGHT: Execute → Validate (Haiku → Haiku) - micro-tasks
 * - LOW: Execute → Validate (Sonnet → Haiku) - simple tasks  
 * - MEDIUM: Plan → Execute → Validate (Sonnet → Sonnet → Haiku) - standard
 * - HIGH: Plan → Execute → Validate (Opus → Sonnet → Haiku) - complex
 * 
 * + EPIC mode for long prompts (500+ words):
 *   Intake → Analyze → Plan → [Stage_N...] → Validate → Preview
 */

// Re-export types for backward compatibility
export type PipelineMode = BasePipelineMode;
export type PipelinePhase = BasePipelinePhase | 'plan' | 'execute' | 'validate';

